# week80-1: route node diagram (jia->yi 2, bing->ding 2, jia->bing 4, yi->ding 3)
draw1=function(){
  plot(0,0,xlim=c(0,10),ylim=c(0,10),type="n",asp=1,xlab="",ylab="",axes=FALSE)
  # nodes: jia(2,8), yi(8,8), bing(2,2), ding(8,2)
  # horizontal top: jia->yi 2 parallel lines (slightly offset)
  segments(2.3,8.2,7.7,8.2,lwd=1.5)
  segments(2.3,7.8,7.7,7.8,lwd=1.5)
  # horizontal bottom: bing->ding 2 parallel lines
  segments(2.3,2.2,7.7,2.2,lwd=1.5)
  segments(2.3,1.8,7.7,1.8,lwd=1.5)
  # vertical left: jia->bing 4 parallel lines
  segments(1.2,2.3,1.2,7.7,lwd=1.5)
  segments(1.6,2.3,1.6,7.7,lwd=1.5)
  segments(2.0,2.3,2.0,7.7,lwd=1.5)
  segments(2.4,2.3,2.4,7.7,lwd=1.5)
  # vertical right: yi->ding 3 parallel lines
  segments(7.6,2.3,7.6,7.7,lwd=1.5)
  segments(8.0,2.3,8.0,7.7,lwd=1.5)
  segments(8.4,2.3,8.4,7.7,lwd=1.5)
  # node circles
  symbols(2,8,circles=0.35,inches=FALSE,add=TRUE,lwd=1.5)
  symbols(8,8,circles=0.35,inches=FALSE,add=TRUE,lwd=1.5)
  symbols(2,2,circles=0.35,inches=FALSE,add=TRUE,lwd=1.5)
  symbols(8,2,circles=0.35,inches=FALSE,add=TRUE,lwd=1.5)
  text(2,8,"J",cex=1.3,font=2)
  text(8,8,"Y",cex=1.3,font=2)
  text(2,2,"B",cex=1.3,font=2)
  text(8,2,"D",cex=1.3,font=2)
}
cairo_pdf("../figures/week80-1.pdf",width=4,height=4,family="SimSun")
draw1()
dev.off()
svglite::svglite("../figures/week80-1.svg",width=4,height=4)
