# week80-2: circuit diagram A to B with 3 parallel branches
draw2=function(){
  plot(0,0,xlim=c(0,12),ylim=c(0,10),type="n",asp=1,xlab="",ylab="",axes=FALSE)
  # A node at (0.5,5), B node at (11.5,5)
  # vertical bus left at x=1 from y=2 to y=8, right at x=11
  segments(1,2,1,8,lwd=1.5)
  segments(11,2,11,8,lwd=1.5)
  segments(0.2,5,1,5,lwd=1.5)
  segments(11,5,11.8,5,lwd=1.5)
  symbols(0.2,5,circles=0.25,inches=FALSE,add=TRUE,lwd=1.5)
  symbols(11.8,5,circles=0.25,inches=FALSE,add=TRUE,lwd=1.5)
  text(0.2,5,"A",pos=2,cex=1.3)
  text(11.8,5,"B",pos=4,cex=1.3)
  # switch symbol: two circles with a diagonal line between, at given center
  sw=function(x,y){
    segments(x-0.35,y,x-0.15,y,lwd=1.5)
    segments(x+0.15,y,x+0.35,y,lwd=1.5)
    symbols(x-0.15,y,circles=0.08,inches=FALSE,add=TRUE,lwd=1.5)
    symbols(x+0.15,y,circles=0.08,inches=FALSE,add=TRUE,lwd=1.5)
    segments(x-0.15,y,x+0.05,y+0.25,lwd=1.5)
  }
  # top branch y=8: (two parallel switches) series (two parallel switches)
  segments(1,8,3,8,lwd=1.5)
  sw(3.5,8); sw(4.2,8)
  segments(4.6,8,5.5,8,lwd=1.5)
  # parallel group 1: small bridge
  segments(3.85,8.35,3.85,7.65,lwd=1)
  segments(3.5,8.35,4.2,8.35,lwd=1)
  segments(3.5,7.65,4.2,7.65,lwd=1)
  sw(6.5,8); sw(7.2,8)
  segments(7.6,8,11,8,lwd=1.5)
  segments(6.85,8.35,6.85,7.65,lwd=1)
  segments(6.5,8.35,7.2,8.35,lwd=1)
  segments(6.5,7.65,7.2,7.65,lwd=1)
  # middle branch y=5: single switch
  sw(6,5)
  segments(1,5,5.6,5,lwd=1.5)
  segments(6.4,5,11,5,lwd=1.5)
  # bottom branch y=2: same as top
  segments(1,2,3,2,lwd=1.5)
  sw(3.5,2); sw(4.2,2)
  segments(4.6,2,5.5,2,lwd=1.5)
  segments(3.85,2.35,3.85,1.65,lwd=1)
  segments(3.5,2.35,4.2,2.35,lwd=1)
  segments(3.5,1.65,4.2,1.65,lwd=1)
  sw(6.5,2); sw(7.2,2)
  segments(7.6,2,11,2,lwd=1.5)
  segments(6.85,2.35,6.85,1.65,lwd=1)
  segments(6.5,2.35,7.2,2.35,lwd=1)
  segments(6.5,1.65,7.2,1.65,lwd=1)
}
cairo_pdf("../figures/week80-2.pdf",width=4,height=4,family="SimSun")
draw2()
dev.off()
svglite::svglite("../figures/week80-2.svg",width=4,height=4)
draw2()
