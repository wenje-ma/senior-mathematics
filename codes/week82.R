# week82-1: tree flowchart of binomial theorem history (single 4x4, vertical)
draw1=function(){
  par(mar=c(1,1,1,1))
  plot(0,0,xlim=c(0,14),ylim=c(0,12),type="n",asp=1,xlab="",ylab="",axes=FALSE)
  bx=function(x,y,txt,w=2.6,h=0.7){
    rect(x-w/2,y-h/2,x+w/2,y+h/2,lwd=1.2)
    text(x,y,txt,cex=0.7)
  }
  bx(7,11.2,"Euclid")
  bx(7,9.6,"Jiuzhang")
  arrows(7,10.8,7,10.0,lwd=1)
  bx(7,8.0,"Pascal")
  arrows(7,9.2,7,8.4,lwd=1)
  bx(3.5,6.3,"Newton")
  bx(10.5,6.3,"Leibniz")
  arrows(5.5,7.6,4.2,6.7,lwd=1)
  arrows(8.5,7.6,9.8,6.7,lwd=1)
  bx(7,4.6,"18th c.")
  arrows(4.0,5.9,6.0,5.0,lwd=1)
  arrows(10.0,5.9,8.0,5.0,lwd=1)
  bx(2.5,2.9,"Montmort")
  bx(7,2.9,"Castillon")
  bx(11.5,2.9,"Euler")
  arrows(6.0,4.2,3.2,3.3,lwd=1)
  arrows(7,4.2,7,3.3,lwd=1)
  arrows(8.0,4.2,10.8,3.3,lwd=1)
  bx(7,1.1,"Cauchy")
  arrows(2.8,2.5,5.5,1.5,lwd=1)
  arrows(7,2.5,7,1.5,lwd=1)
  arrows(11.2,2.5,8.5,1.5,lwd=1)
}
cairo_pdf("../figures/week82-1.pdf",width=4,height=4,family="SimSun")
