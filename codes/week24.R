# week24: trigonometric models (24-1..24-4)
draw1=function(){
  t=seq(0,4,len=300)
  plot(t,3*sin(pi*t),type="l",lwd=2,ylim=c(-3.5,3.5),xlab="t/s",ylab="y/cm")
  abline(h=0,lty=3)
}
