# week30: review trig graphs (30-1..30-3)
draw1=function(){
  par(mfrow=c(2,2),mar=c(4,4,2,1))
  curve(0.5*sin(3*x-pi/3),pi/9,pi/9+2*pi/3,lwd=2,xlab="x",ylab="y",main="(1)",ylim=c(-0.6,0.6))
  abline(h=0,lty=3)
  curve(-2*sin(x+pi/4),-pi/4,-pi/4+2*pi,lwd=2,xlab="x",ylab="y",main="(2)",ylim=c(-2.2,2.2))
  abline(h=0,lty=3)
  curve(1-sin(2*x-pi/5),pi/10,pi/10+pi,lwd=2,xlab="x",ylab="y",main="(3)",ylim=c(0,2))
  abline(h=0,lty=3)
  curve(3*sin(x/6-pi/3),2*pi,2*pi+12*pi,lwd=2,xlab="x",ylab="y",main="(4)",ylim=c(-3.2,3.2))
  abline(h=0,lty=3)
}
pdf("../figures/week30-1.pdf",width=8,height=8);draw1();dev.off()
svglite::svglite("../figures/week30-1.svg",width=8,height=8);draw1();dev.off()
draw2=function(){
  x=seq(0,pi/2,len=100)
  plot(x,sin(x),type="o",pch=19,lwd=2,ylim=c(0,1.1),xlab="x",ylab="y")
  abline(h=0,v=0,lty=3)
}
pdf("../figures/week30-2.pdf",width=4,height=4);draw2();dev.off()
svglite::svglite("../figures/week30-2.svg",width=4,height=4);draw2();dev.off()
draw3=function(){
  a=seq(0.1,pi/2-0.1,len=200)
  plot(a,1/sin(2*a),type="l",lwd=2,ylim=c(0,6),xlab=expression(alpha),ylab="S",xaxt="n")
  abline(h=0,v=0,lty=3)
  axis(1,at=c(0,pi/4,pi/2),labels=expression(0,pi/4,pi/2))
}
