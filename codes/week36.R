# week36: 7.2 complex arithmetic
# week36-1: Ex7.2 q2 given vector OZ=z, draw (1) z+1 (2) z-i (3) z+(-2+i)
draw1=function(){
  par(mfrow=c(1,3),mar=c(3,3,2,1))
  z=c(2,1.5)
  plot(0,0,xlim=c(-0.5,3.8),ylim=c(-0.5,2.5),type="n",asp=1,xlab="x",ylab="y",main="(1)")
  abline(h=0,v=0,lty=3)
  arrows(0,0,z[1],z[2],lty=2,lwd=1,length=0.07)
  arrows(0,0,z[1]+1,z[2],lwd=2,length=0.07)
  points(z[1]+1,z[2],pch=19);text(z[1]+1+0.1,z[2]+0.1,"Z'")
  plot(0,0,xlim=c(-0.5,3),ylim=c(-1.2,2.5),type="n",asp=1,xlab="x",ylab="y",main="(2)")
  abline(h=0,v=0,lty=3)
  arrows(0,0,z[1],z[2],lty=2,lwd=1,length=0.07)
  arrows(0,0,z[1],z[2]-1,lwd=2,length=0.07)
  points(z[1],z[2]-1,pch=19);text(z[1]+0.1,z[2]-1+0.1,"Z'")
  plot(0,0,xlim=c(-2.5,2.8),ylim=c(-0.8,3.2),type="n",asp=1,xlab="x",ylab="y",main="(3)")
  abline(h=0,v=0,lty=3)
  arrows(0,0,z[1],z[2],lty=2,lwd=1,length=0.07)
  arrows(0,0,z[1]-2,z[2]+1,lwd=2,length=0.07)
  points(z[1]-2,z[2]+1,pch=19);text(z[1]-2+0.1,z[2]+1+0.1,"Z'")
}
pdf("../figures/week36-1.pdf",width=12,height=4);draw1();dev.off()
svglite::svglite("../figures/week36-1.svg",width=12,height=4);draw1();dev.off()
