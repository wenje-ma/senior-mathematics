# week4-1: two horizontal lines a,b cut by transversal l; angles 1,2,3,4
draw1=function(){
  plot(0,0,xlim=c(0,10),ylim=c(0,8),type="n",asp=1,axes=FALSE,xlab="",ylab="")
  segments(1,6,9,6,lwd=1.5)
  segments(1,2,9,2,lwd=1.5)
  segments(4.2,7.5,6.2,0.5,lwd=1.5)
  text(1.0,6.3,"a",pos=2,font=3)
  text(1.0,2.3,"b",pos=2,font=3)
  text(4.0,7.4,"l",pos=2,font=3)
  text(4.7,6.4,"4")
  text(5.9,6.4,"2")
  text(4.7,5.6,"3")
  text(6.1,1.6,"1")
}
cairo_pdf("../figures/week4-1.pdf",width=4,height=4,family="SimSun")
draw1()
dev.off()
svglite::svglite("../figures/week4-1.svg",width=4,height=4)
draw1()
dev.off()
# week4-2: trapezoid ABCD with diagonals AC, BD (AD top short, BC bottom long)
draw2=function(){
  plot(0,0,xlim=c(0,10),ylim=c(0,8),type="n",asp=1,axes=FALSE,xlab="",ylab="")
  A=c(3.5,6.5);B=c(1.5,1.5);C=c(8.5,1.5);D=c(6.5,6.5)
  polygon(c(A[1],B[1],C[1],D[1]),c(A[2],B[2],C[2],D[2]),lwd=1.5)
  segments(A[1],A[2],C[1],C[2],lwd=1.5)
  segments(B[1],B[2],D[1],D[2],lwd=1.5)
  text(A[1],A[2],"A",pos=3,font=2)
  text(B[1],B[2],"B",pos=2,font=2)
  text(C[1],C[2],"C",pos=4,font=2)
  text(D[1],D[2],"D",pos=3,font=2)
}
cairo_pdf("../figures/week4-2.pdf",width=4,height=4,family="SimSun")
draw2()
dev.off()
svglite::svglite("../figures/week4-2.svg",width=4,height=4)
draw2()
dev.off()
