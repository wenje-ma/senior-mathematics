# week14: exponential functions (14-1,14-2,14-3)
draw1=function(){
  x=seq(-2,2,len=300)
  plot(x,3^x,type="l",lty=1,lwd=2,ylim=c(0,9),xlab="x",ylab="y",las=1)
  lines(x,(1/3)^x,lty=2,lwd=2)
  abline(h=0,v=0,lty=3)
  points(0,1,pch=19)
  text(1.0,6.5,expression(y==3^x))
  text(-2.0,6.5,expression(y==(1/3)^x))
}
pdf("../figures/week14-1.pdf",width=4,height=4)
draw1()
dev.off()
svglite::svglite("../figures/week14-1.svg",width=4,height=4)
draw1()
dev.off()
