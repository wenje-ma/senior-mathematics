# week23: y=A sin(wx+phi) transformations (23-1..23-3)
draw1=function(){
  par(mfrow=c(2,2),mar=c(4,4,2,1))
  curve(0.5*sin(x),0,2*pi,lwd=2,xlab="x",ylab="y",main="(1)",ylim=c(-1,1))
  abline(h=0,lty=3)
  curve(sin(3*x),0,2*pi/3,lwd=2,xlab="x",ylab="y",main="(2)",ylim=c(-1,1))
  abline(h=0,lty=3)
  curve(sin(x-pi/3),pi/3,pi/3+2*pi,lwd=2,xlab="x",ylab="y",main="(3)",ylim=c(-1,1))
  abline(h=0,lty=3)
  curve(2*sin(2*x-pi/4),pi/8,pi/8+pi,lwd=2,xlab="x",ylab="y",main="(4)",ylim=c(-2.2,2.2))
  abline(h=0,lty=3)
}
pdf("../figures/week23-1.pdf",width=8,height=8);draw1();dev.off()
svglite::svglite("../figures/week23-1.svg",width=8,height=8);draw1();dev.off()
