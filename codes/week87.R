# week87-1: two normal density curves N(0,2^2) solid, N(0,3^2) dashed
draw1=function(){
  par(mar=c(4,4,2,1))
  x=seq(-10,10,length.out=200)
  y1=dnorm(x,mean=0,sd=2)
  y2=dnorm(x,mean=0,sd=3)
  plot(x,y1,type="l",lwd=2,lty=1,xlab="x",ylab="density",main="",ylim=c(0,0.22))
  lines(x,y2,lwd=2,lty=2)
  abline(v=0,lty=3)
  legend("topright",legend=c("N(0,2^2)","N(0,3^2)"),lty=c(1,2),lwd=2,bty="n")
}
cairo_pdf("../figures/week87-1.pdf",width=4,height=4,family="SimSun")
draw1()
dev.off()
